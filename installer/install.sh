#!/usr/bin/env bash
# CheckMyRender installer: per user, no sudo, own conda environment. Run it from an unpacked
# release bundle (cmr-<version>/install.sh). Design and flags: installer/CLAUDE.md.
#
# Production Python policy (root CLAUDE.md D2): never update or replace the system Python on
# production machines; cmr runs from its own conda environment. This script never runs sudo,
# never pip-installs into a Python other than <prefix>/env, never pipes a download into a
# shell, and never changes conda's base or any other environment.
set -u -o pipefail
# Runs on bash 3.2 (macOS /bin/bash, D32) and on Linux bash 4/5: no associative arrays, no
# mapfile, empty arrays expanded as ${a[@]+"${a[@]}"}, BSD/GNU-neutral tool options (sha256 via
# sha256sum or `shasum -a 256`, no `date %N`, no `grep \s`, POSIX character classes).

PROG=install.sh
MIN_FFMPEG_MAJOR=5 MIN_FFMPEG_MINOR=1      # oldest system ffmpeg accepted with --use-system-ffmpeg (5.1.10, Rocky 9)
CHANNEL=conda-forge                        # every conda package comes from here only
NEED_MB_SLATE=3072 NEED_MB_NOSLATE=2048 NEED_MB_UPDATE=512   # free space checks (estimates; measured 2026-10-26:
# env ffmpeg 7.1 + tesseract 1.2 GB + ~0.56 GB package cache, --no-slate env with ffmpeg 765 MB + cache)
NEED_MB_ADD_FFMPEG=1024   # update that adds ffmpeg to an existing env (measured ~0.7 GB, migration run)
NEED_MB_DEMO=512          # demo spots not created yet: Pillow + numpy (+ cache) and ~190 MB of media in the workspace
# Miniforge is pinned: only the versioned release files have a `.sha256` next to them
# (releases/latest/download/Miniforge3-<platform>.sh.sha256 is a 404; checked 2026-10-26)
MINIFORGE_VERSION=26.9.4-0
MINIFORGE_BASE=https://github.com/conda-forge/miniforge/releases/download/$MINIFORGE_VERSION
POLICY="Production Python policy: the system Python was not touched and must never be updated
or replaced on a production machine (Flame and the OS rely on it). CheckMyRender runs from its
own conda environment."
LAUNCHER_MARK="# CheckMyRender launcher (generated by install.sh)"
PREFIX_MARK=".cmr-install-prefix"

BUNDLE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
PREFIX="$HOME/.local/share/cmr"
WORKSPACE="$HOME/cmr-workspace"
BIN_DIR="$HOME/.local/bin"
BIN_DIR_SET=0 WORKSPACE_SET=0
DRY=0 YES=0 SLATE=1 DEMO=1 UPGRADE=0 UNINSTALL=0 BOOTSTRAP=0 OFFLINE_DIR="" USE_SYSTEM_FF=0
STEP=0 STEPS=10

usage() {
    cat <<EOF
Usage: $PROG [options]

Installs CheckMyRender for the current user (no sudo): a conda environment with Python 3.12,
the cmr package, tesseract (slate OCR) and the pinned, tested ffmpeg (conda-forge 7.1.1, so
every machine gives comparable results; the system ffmpeg is never changed); a 'cmr' launcher
in ~/.local/bin; examples/templates in a workspace folder, with demo spots to try cmr on.

Options:
  --prefix DIR        install location (default ~/.local/share/cmr; env in DIR/env)
  --workspace DIR     where examples/ and templates/ are copied (default ~/cmr-workspace)
  --bin-dir DIR       where the 'cmr' launcher goes (default ~/.local/bin)
                      (a re-run, --upgrade or --uninstall of the same --prefix reuses the
                      previous --workspace and --bin-dir unless they are given again)
  --no-slate          do not install tesseract (slate OCR checks then report ERROR)
  --no-demo           do not create the demo spots (a clean slated spot in
                      templates/starter/media and spots with planted errors in demo_spots/,
                      ~190 MB, ~10-60 s) and do not install Pillow/numpy, which only the demo
                      generator needs; demo files are created once and never overwritten
  --use-system-ffmpeg use the system ffmpeg/ffprobe instead of the pinned 7.1.1 when it is
                      >= 5.1 with every required filter (results may differ from the tested
                      7.1.1); give it on every run, a run without it switches to 7.1.1
  --upgrade           refresh the environment and reinstall cmr even if this version is installed
  --uninstall         remove the environment, launcher and prefix (asks first)
  --bootstrap-conda   if no conda is found, install Miniforge into DIR/conda without asking
  --offline-dir DIR   offline install from a package cache (planned, not built yet)
  -y, --yes           answer yes to every question
  -n, --dry-run       print every action, change nothing
  -h, --help          this help

Exit codes: 0 done, 1 failed (see the log), 2 usage/unsupported, 3 cancelled.
EOF
}

# --- output and log (log line style of D29) ------------------------------------------------
RUN_ID=$(od -An -N3 -tx1 /dev/urandom 2>/dev/null | tr -d ' \n')
LOG_DIR="${XDG_CACHE_HOME:-$HOME/.cache}/cmr/logs"
# macOS: cmr logs to ~/Library/Logs/cmr (D32; an explicit XDG_CACHE_HOME still wins, as in cmr)
[ "$(uname -s)" = Darwin ] && [ -z "${XDG_CACHE_HOME:-}" ] && LOG_DIR="$HOME/Library/Logs/cmr"
LOG=/dev/null
# milliseconds: GNU date only (BSD date prints "3N"); elsewhere .000
case $(date +%3N 2>/dev/null) in [0-9][0-9][0-9]) DATE_FMT='+%Y-%m-%d %H:%M:%S.%3N';; *) DATE_FMT='+%Y-%m-%d %H:%M:%S.000';; esac

log() {   # log LEVEL MESSAGE
    local lvl=$1; shift
    case $lvl in INFO|WARN) lvl="$lvl ";; esac
    printf '%s %s install[%s/%s] run=%s file=- | %s\n' "$(date "$DATE_FMT")" \
        "$lvl" "$$" "$$" "${RUN_ID:--}" "${*//$'\n'/ }" >>"$LOG"
}
say()  { printf '%s\n' "$*"; log INFO "$*"; }
warn() { printf 'WARNING: %s\n' "$*" >&2; log WARN "$*"; }
step() { STEP=$((STEP + 1)); printf '\n[%d/%d] %s\n' "$STEP" "$STEPS" "$*"; log INFO "step $STEP/$STEPS: $*"; }
die()  {   # die MESSAGE [HINT] [EXIT]
    printf '\nERROR: %s\n' "$1" >&2; log ERROR "$1"
    [ -n "${2:-}" ] && { printf 'Next step: %s\n' "$2" >&2; log ERROR "hint: $2"; }
    [ "$LOG" != /dev/null ] && printf 'Install log (kept): %s\n' "$LOG" >&2
    exit "${3:-1}"
}
qcmd() { local s="" a; for a in "$@"; do s+="${s:+ }$(printf '%q' "$a")"; done; printf '%s' "$s"; }

run() {   # run CMD...: logged; output to the log only; printed instead of run in --dry-run
    if ((DRY)); then printf '  [dry-run] %s\n' "$(qcmd "$@")"; return 0; fi
    log INFO "run: $(qcmd "$@")"
    local t0=$SECONDS rc
    "$@" >>"$LOG" 2>&1; rc=$?
    log INFO "exit $rc after $((SECONDS - t0)) s"
    return $rc
}
run_live() {   # like run, but the output is also shown (conda solves take minutes)
    if ((DRY)); then printf '  [dry-run] %s\n' "$(qcmd "$@")"; return 0; fi
    log INFO "run: $(qcmd "$@")"
    local t0=$SECONDS rc
    "$@" 2>&1 | tee -a "$LOG"; rc=${PIPESTATUS[0]}
    log INFO "exit $rc after $((SECONDS - t0)) s"
    return $rc
}
act() {   # act DESCRIPTION: announce a file-system action (dry-run: only announce)
    if ((DRY)); then printf '  [dry-run] would %s\n' "$*"; else log INFO "$*"; fi
}
ask() {   # ask QUESTION -> 0 yes / 1 no (stdin; EOF = no)
    if ((YES)); then say "$1 -> yes (--yes)"; return 0; fi
    if ((DRY)); then printf '  [dry-run] would ask: %s (assuming yes)\n' "$1"; return 0; fi
    local ans=""
    printf '%s [y/N] ' "$1"
    read -r ans || ans=""
    log INFO "asked: $1 -> '${ans}'"
    case $ans in [yY]|[yY][eE][sS]) return 0;; *) return 1;; esac
}
shq() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }

# --- arguments ------------------------------------------------------------------------------
while [ $# -gt 0 ]; do
    case $1 in
        --prefix) [ $# -ge 2 ] || die "--prefix needs a directory" "$PROG --help" 2; PREFIX=$2; shift;;
        --prefix=*) PREFIX=${1#*=};;
        --workspace) [ $# -ge 2 ] || die "--workspace needs a directory" "$PROG --help" 2; WORKSPACE=$2; WORKSPACE_SET=1; shift;;
        --workspace=*) WORKSPACE=${1#*=}; WORKSPACE_SET=1;;
        --bin-dir) [ $# -ge 2 ] || die "--bin-dir needs a directory" "$PROG --help" 2; BIN_DIR=$2; BIN_DIR_SET=1; shift;;
        --bin-dir=*) BIN_DIR=${1#*=}; BIN_DIR_SET=1;;
        --offline-dir) [ $# -ge 2 ] || die "--offline-dir needs a directory" "$PROG --help" 2; OFFLINE_DIR=$2; shift;;
        --offline-dir=*) OFFLINE_DIR=${1#*=};;
        --no-slate) SLATE=0;;
        --no-demo) DEMO=0;;
        --use-system-ffmpeg) USE_SYSTEM_FF=1;;
        --upgrade) UPGRADE=1;;
        --uninstall) UNINSTALL=1;;
        --bootstrap-conda) BOOTSTRAP=1;;
        -y|--yes) YES=1;;
        -n|--dry-run) DRY=1;;
        -h|--help) usage; exit 0;;
        *) die "unknown option: $1" "$PROG --help" 2;;
    esac
    shift
done
# platform: Linux x86_64 and macOS on Apple silicon (D32). Intel Macs and Rosetta are refused:
# under Rosetta uname -m says x86_64 and sysctl.proc_translated is 1.
OS=$(uname -s) ARCH=$(uname -m)
translated=0
[ "$OS" = Darwin ] && [ "$( (sysctl -n sysctl.proc_translated || /usr/sbin/sysctl -n sysctl.proc_translated) 2>/dev/null)" = 1 ] && translated=1
case "$OS/$ARCH/$translated" in
    Linux/x86_64/0) MINIFORGE_PLATFORM=Linux-x86_64;;
    Darwin/arm64/0) MINIFORGE_PLATFORM=MacOSX-arm64;;
    Darwin/*/1) die "this shell runs under Rosetta (x86_64 emulation); nothing was changed" \
                    "open a native Terminal (not 'Open using Rosetta') and run the installer again: CheckMyRender supports Apple silicon natively only" 2;;
    Darwin/*) die "unsupported platform $OS/$ARCH (Intel Mac); nothing was changed" \
                  "CheckMyRender on macOS needs Apple silicon (arm64)" 2;;
    *) die "unsupported platform $OS/$ARCH; nothing was changed" \
           "CheckMyRender installs on Linux x86_64 (Rocky Linux 9 tested) and macOS on Apple silicon; Windows is out of scope" 2;;
esac
MINIFORGE_URL="$MINIFORGE_BASE/Miniforge3-$MINIFORGE_VERSION-$MINIFORGE_PLATFORM.sh"
abspath() { case $1 in /*) printf '%s' "${1%/}";; *) printf '%s/%s' "$PWD" "${1%/}";; esac; }
PREFIX=$(abspath "$PREFIX"); WORKSPACE=$(abspath "$WORKSPACE"); BIN_DIR=$(abspath "$BIN_DIR")
[ -n "$PREFIX" ] && [ "$PREFIX" != "$HOME" ] && case "$HOME/" in "$PREFIX/"*) false;; *) true;; esac \
    || die "refusing --prefix $PREFIX (it must be a folder of its own, not / or your home)" \
           "use e.g. --prefix $HOME/.local/share/cmr" 2
[ "$(id -u)" = 0 ] && die "do not run the installer as root or with sudo: it installs per user" \
    "run it as the user who will run cmr" 2
if [ -n "$OFFLINE_DIR" ]; then   # hook for a later offline package cache (conda --offline + file:// channel)
    die "offline install (--offline-dir) is planned but not built yet" \
        "install online, or ask for an offline bundle" 2
fi
ENV="$PREFIX/env"
FFBIN="$PREFIX/ffmpeg-bin"     # ffmpeg/ffprobe symlinks the launcher puts first on PATH
OLD_FFENV="$PREFIX/ffmpeg-env" # older layout (conda-forge ffmpeg 6.1 could not share an env with tesseract
                               # 5.5): migrated on the next run, ffmpeg goes into $ENV and this is removed
STATE="$PREFIX/install-state"

if ((!DRY)); then
    if mkdir -p "$LOG_DIR" 2>/dev/null && touch "$LOG_DIR/install.log" 2>/dev/null; then
        LOG="$LOG_DIR/install.log"
        if [ "$(wc -c <"$LOG")" -gt 5000000 ]; then mv -f "$LOG" "$LOG.1"; fi
    else
        printf 'WARNING: cannot write %s; logging to stderr only\n' "$LOG_DIR" >&2
        LOG=/dev/stderr
    fi
fi
log INFO "=== $PROG start: $(qcmd "$0" "$@") bundle=$BUNDLE prefix=$PREFIX workspace=$WORKSPACE dry=$DRY"
((DRY)) && say "DRY RUN: nothing will be changed; every action is printed."

# --- state of a previous install -----------------------------------------------------------
old() {   # old KEY: value from the state file of the previous install (empty if none)
    [ -f "$STATE" ] && awk -v k="$1" 'index($0, k "=") == 1 {v = substr($0, length(k) + 2)} END {printf "%s", v}' "$STATE"
}
# the launcher folder and workspace of the previous install win unless given again
((BIN_DIR_SET)) || [ -z "$(old bin_dir)" ] || BIN_DIR=$(old bin_dir)
((WORKSPACE_SET)) || [ -z "$(old workspace)" ] || WORKSPACE=$(old workspace)
LAUNCHER="$BIN_DIR/cmr"

# --- uninstall ------------------------------------------------------------------------------
if ((UNINSTALL)); then
    STEPS=1; step "Uninstall CheckMyRender from $PREFIX"
    [ -d "$PREFIX" ] || { say "Nothing installed at $PREFIX."; exit 0; }
    [ -f "$PREFIX/$PREFIX_MARK" ] || die "$PREFIX was not created by this installer; nothing removed" \
        "check --prefix" 1
    say "This removes: $PREFIX (conda environment, ffmpeg links, state$( [ -d "$PREFIX/conda" ] && printf ', bootstrapped Miniforge'))"
    grep -qF "$LAUNCHER_MARK" "$LAUNCHER" 2>/dev/null && say "and the launcher $LAUNCHER"
    say "Kept: your workspace ($WORKSPACE) and the logs ($LOG_DIR)."
    [ -f "$WORKSPACE/.cmr-demo-files" ] && say "      The demo spots stay in the workspace too (delete $WORKSPACE/demo_spots yourself if you do not need them)."
    ask "Remove CheckMyRender?" || { say "Cancelled, nothing removed."; exit 3; }
    if grep -qF "$LAUNCHER_MARK" "$LAUNCHER" 2>/dev/null; then
        act "remove $LAUNCHER"; ((DRY)) || rm -f "$LAUNCHER"
    fi
    act "remove $PREFIX"; ((DRY)) || rm -rf "$PREFIX"
    say "CheckMyRender removed."
    exit 0
fi

say "CheckMyRender installer (per user, no sudo)"
say "$POLICY"

# --- 1. preflight ---------------------------------------------------------------------------
step "Check this machine"
log INFO "os=$OS arch=$ARCH $( [ -r /etc/os-release ] && . /etc/os-release && printf '%s' "${PRETTY_NAME:-}")$( [ "$OS" = Darwin ] && printf 'macOS %s' "$(sw_vers -productVersion 2>/dev/null)")"
say "  OS: $OS $ARCH - supported"
for t in df mktemp grep sed awk cmp find sort tee; do
    command -v "$t" >/dev/null || die "required tool '$t' not found" "install coreutils/findutils/tar" 1
done
if command -v sha256sum >/dev/null; then SHA256=(sha256sum)          # GNU coreutils
elif command -v shasum >/dev/null; then SHA256=(shasum -a 256)       # macOS (same output/-c format)
else die "required tool 'sha256sum' (or 'shasum') not found" "install coreutils" 1; fi

VERSION=$(cat "$BUNDLE/VERSION" 2>/dev/null) WHEEL=""
for w in "$BUNDLE"/wheels/*.whl; do [ -f "$w" ] && WHEEL=$w; done
[ -n "$VERSION" ] && [ -n "$WHEEL" ] && [ -f "$BUNDLE/SHA256SUMS" ] && [ -f "$BUNDLE/required_filters.txt" ] \
    && [ -f "$BUNDLE/environment.yml" ] \
    || die "this is not a complete release bundle (VERSION, wheels/*.whl, SHA256SUMS, environment.yml, required_filters.txt)" \
           "unpack cmr-<version>-bundle.tar.gz and run cmr-<version>/install.sh (build one with installer/build_bundle.sh)" 1
grep -q " wheels/$(basename "$WHEEL")\$" "$BUNDLE/SHA256SUMS" \
    || die "the wheel is not listed in SHA256SUMS" "download the bundle again" 1
if ! (cd "$BUNDLE" && "${SHA256[@]}" -c --quiet SHA256SUMS) >>"$LOG" 2>&1; then
    die "bundle checksum mismatch (SHA256SUMS): the download is damaged or was changed" "download the bundle again" 1
fi
say "  Bundle: cmr $VERSION, checksums ok ($(basename "$WHEEL"))"

if [ -e "$PREFIX" ] && [ ! -f "$PREFIX/$PREFIX_MARK" ] && [ -n "$(ls -A "$PREFIX" 2>/dev/null)" ]; then
    die "$PREFIX exists, is not empty and was not created by this installer" \
        "choose another --prefix, or empty that folder yourself" 1
fi
if [ -e "$LAUNCHER" ] && ! grep -qF "$LAUNCHER_MARK" "$LAUNCHER" 2>/dev/null; then
    die "$LAUNCHER exists and is not a CheckMyRender launcher (old manual install?)" \
        "rename or remove $LAUNCHER, then run the installer again" 1
fi
MODE=install
OLD_VERSION=$(old version)
if [ -n "$OLD_VERSION" ] && [ -x "$ENV/bin/python" ]; then
    if [ "$OLD_VERSION" != "$VERSION" ]; then MODE=upgrade
    elif ((UPGRADE)); then MODE=refresh
    else MODE=same; fi
fi
case $MODE in
    install) say "  New install into $PREFIX";;
    upgrade) say "  Upgrade in place: cmr $OLD_VERSION -> $VERSION";;
    refresh) say "  cmr $VERSION is installed; --upgrade: refreshing the environment and reinstalling";;
    same)    say "  cmr $VERSION is already installed: re-checking links, workspace and health (--upgrade to refresh packages)";;
esac

need=$NEED_MB_NOSLATE; ((SLATE)) && need=$NEED_MB_SLATE
[ "$MODE" = install ] || need=$NEED_MB_UPDATE
# an existing env without ffmpeg (system-ffmpeg install, old ffmpeg-env layout) gets it added
[ "$MODE" != install ] && ((!USE_SYSTEM_FF)) && [ ! -x "$ENV/bin/ffmpeg" ] && need=$NEED_MB_ADD_FFMPEG
# demo spots not created into this workspace yet (no record): Pillow/numpy + media to come
DEMO_LIST="$WORKSPACE/.cmr-demo-files"
DEMO_TODO=0; ((DEMO)) && [ ! -f "$DEMO_LIST" ] && DEMO_TODO=1
((DEMO_TODO)) && need=$((need + NEED_MB_DEMO))
d=$PREFIX; while [ ! -d "$d" ]; do d=$(dirname "$d"); done
avail=$(df -Pk "$d" 2>/dev/null | awk 'NR==2 {print int($4/1024)}')
[ -n "$avail" ] || die "cannot read the free disk space of $d (df failed)" "check that $d is a mounted file system" 1
log INFO "free space $avail MB on the file system of $d, need $need MB"
if [ "$avail" -lt "$need" ]; then
    die "not enough free disk space: $avail MB free on the file system of $d, about $need MB needed" \
        "free some space, choose another disk with --prefix DIR$( ((SLATE)) && printf ', or skip the slate OCR (~0.9 GB with the conda package cache) with --no-slate')$( ((DEMO_TODO)) && printf ', or skip the demo spots with --no-demo')" 1
fi
say "  Disk: $avail MB free, about $need MB needed"

# --- 2. conda -------------------------------------------------------------------------------
step "Find conda (base and other environments are never changed)"
conda_ok() { [ -n "$1" ] && [ -x "$1" ] && "$1" --version >/dev/null 2>&1; }
CONDA="" CONDA_FROM=""
try_conda() { [ -z "$CONDA" ] && conda_ok "$1" && { CONDA=$1; CONDA_FROM=$2; }; return 0; }
try_conda "$(old conda)" "previous install"
try_conda "$(command -v conda 2>/dev/null)" "PATH"
for c in "$HOME/Tools/anaconda3" "$HOME/anaconda3" "$HOME/miniconda3" "$HOME/miniforge3"; do
    try_conda "$c/bin/conda" "$c"
done
try_conda "${CONDA_EXE:-}" "CONDA_EXE"
try_conda "$PREFIX/conda/bin/conda" "Miniforge in the prefix"
NEED_BOOTSTRAP=0
if [ -n "$CONDA" ]; then
    say "  Using $CONDA ($("$CONDA" --version 2>&1), found via $CONDA_FROM)"
else
    say "  No conda found (searched: PATH, ~/Tools/anaconda3, ~/anaconda3, ~/miniconda3, ~/miniforge3, \$CONDA_EXE, $PREFIX/conda)."
    say "  Miniforge is a small conda from the conda-forge community (BSD licence, no Anaconda ToS)."
    if ((BOOTSTRAP)) || ask "Install Miniforge into $PREFIX/conda (private to cmr, no shell changes)?"; then
        NEED_BOOTSTRAP=1; CONDA="$PREFIX/conda/bin/conda"; CONDA_FROM="Miniforge bootstrap"
    else
        die "conda is required and none was found" \
            "install Miniforge or Anaconda yourself (or put conda on PATH), or re-run with --bootstrap-conda" 3
    fi
fi

# --- 3. ffmpeg ------------------------------------------------------------------------------
# Default: the pinned conda-forge ffmpeg (environment.yml, `# cmr:ffmpeg`) in cmr's own env on
# every machine, so results are comparable (user decision 2026-10-26: Rocky's 5.1.10 ffprobe
# reported colour tags of ProRes as unknown where 7.1 reads bt709). The system ffmpeg is used only
# with --use-system-ffmpeg and when it passes the acceptance test below; it is never changed.
step "Choose ffmpeg/ffprobe (the system ones are never changed)"
FF_PIN=$(sed -n 's/^ *- *ffmpeg=\([^ #]*\).*# cmr:ffmpeg.*/\1/p' "$BUNDLE/environment.yml" | head -1)
FF_PIN=${FF_PIN:-pinned}
REQ_FILTERS=()
while IFS= read -r f; do REQ_FILTERS[${#REQ_FILTERS[@]}]=$f
done < <(grep -v -e '^[[:space:]]*#' -e '^[[:space:]]*$' "$BUNDLE/required_filters.txt")
find_system() {   # first $1 on PATH outside the cmr prefix
    local IFS=: d
    for d in $PATH; do
        [ -n "$d" ] || continue
        case "$d/" in "$PREFIX/"*|"$BIN_DIR/") continue;; esac
        [ -x "$d/$1" ] && [ ! -d "$d/$1" ] && { printf '%s' "$d/$1"; return 0; }
    done
    return 1
}
ff_version() { "$1" -version 2>/dev/null | head -1 | sed -n 's/^[a-z]* version n\{0,1\}\([0-9][0-9]*\.[0-9][0-9]*\).*/\1/p'; }
version_ok() { local v=$1; [ -n "$v" ] || return 1
    [ "${v%%.*}" -gt "$MIN_FFMPEG_MAJOR" ] || { [ "${v%%.*}" -eq "$MIN_FFMPEG_MAJOR" ] && [ "${v#*.}" -ge "$MIN_FFMPEG_MINOR" ]; }; }
FF_MODE=env FF_PATH="" FP_PATH="" FF_WHY=""
SYS_FF=$(find_system ffmpeg) SYS_FP=$(find_system ffprobe)
if ((USE_SYSTEM_FF)); then   # opt-in: today's acceptance test (>= 5.1, every required filter)
    if [ -z "$SYS_FF" ] || [ -z "$SYS_FP" ]; then
        FF_WHY="ffmpeg/ffprobe not found on PATH"
    else
        vff=$(ff_version "$SYS_FF") vfp=$(ff_version "$SYS_FP")
        log INFO "system ffmpeg $SYS_FF version '$vff', ffprobe $SYS_FP version '$vfp'"
        if ! version_ok "$vff" || ! version_ok "$vfp"; then
            FF_WHY="$SYS_FF version '${vff:-unknown}' / ffprobe '${vfp:-unknown}' is older than $MIN_FFMPEG_MAJOR.$MIN_FFMPEG_MINOR or unreadable"
        else
            # flag columns: T S C up to ffmpeg 7.1, T S from 8.0 (same rule as engine.available_filters)
            have=$("$SYS_FF" -hide_banner -filters 2>/dev/null | sed -n 's/^ [T.][S.][C.]\{0,1\} \([^ ][^ ]*\)  *[^ ][^ ]*->[^ ][^ ]*.*/\1/p')
            miss=""
            for f in ${REQ_FILTERS[@]+"${REQ_FILTERS[@]}"}; do grep -qx -- "$f" <<<"$have" || miss+="${miss:+, }$f"; done
            if [ -n "$miss" ]; then FF_WHY="$SYS_FF $vff lacks filters: $miss"
            else FF_MODE=system FF_PATH=$SYS_FF FP_PATH=$SYS_FP; fi
        fi
    fi
fi
if [ "$FF_MODE" = system ]; then
    say "  --use-system-ffmpeg: $SYS_FF ($vff >= $MIN_FFMPEG_MAJOR.$MIN_FFMPEG_MINOR, all ${#REQ_FILTERS[@]} required filters) - cmr will use it"
    warn "--use-system-ffmpeg: results may differ from the tested ffmpeg $FF_PIN and from other machines (e.g. ffprobe 5.1 reads ProRes colour tags as unknown, other versions differ in other ways); run without the flag to use $FF_PIN"
else
    FF_PATH="$ENV/bin/ffmpeg" FP_PATH="$ENV/bin/ffprobe"
    if ((USE_SYSTEM_FF)); then
        warn "--use-system-ffmpeg: the system ffmpeg cannot be used: $FF_WHY"
        say "  -> installing the pinned $CHANNEL ffmpeg $FF_PIN into cmr's own environment $ENV instead"
    else
        say "  Using the pinned, tested $CHANNEL ffmpeg $FF_PIN in cmr's own environment $ENV (same on every machine)"
        [ "$(old ffmpeg_mode)" = system ] \
            && say "  The previous install used the system ffmpeg ($(old ffmpeg)); switching to $FF_PIN (--use-system-ffmpeg keeps the system one)"
        [ -n "$SYS_FF" ] && say "  System ffmpeg $SYS_FF is not used and not touched (opt in with --use-system-ffmpeg)"
    fi
fi

# --- 4. network -----------------------------------------------------------------------------
step "Check the network ($CHANNEL)"
if ((DRY)); then
    printf '  [dry-run] would check https://conda.anaconda.org/%s/ with curl\n' "$CHANNEL"
elif command -v curl >/dev/null; then
