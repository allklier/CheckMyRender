    spec=$(sed -n 's/^ *- *\([^ #][^ #]*\).*/\1/p' <<<"$line"); [ -n "$spec" ] || continue
    case $line in
        *"# cmr:ffmpeg"*) [ "$FF_MODE" = env ] || continue;;
        *"# cmr:slate"*)  ((SLATE)) || continue;;
        *"# cmr:demo"*)   ((DEMO)) || continue;;
