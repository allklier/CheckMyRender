# --- 7. launcher ----------------------------------------------------------------------------
# The launcher (POSIX sh) is relocatable (D33): it finds its own folder at run time (following
# the PATH link), derives every path from it, runs `python -I -m cmr` (the env's bin/cmr has an
# absolute shebang) and keeps cmr-paths.conf next to it current. It does not read install-state.
step "Write the launcher $LAUNCHER$( ((NO_LINK)) || printf ' and the PATH link %s' "$LINK")"
rel_up() { case $1 in "$NEW_PARENT"/*) printf '%s' "${1#"$NEW_PARENT"/}";; *) printf '%s' "$1";; esac; }
L_ROOTED=0; [ "$PREFIX" = "$ROOT/bin" ] && ((!LEGACY)) && L_ROOTED=1
L_WORK=""; [ -n "$WORK" ] && { ((WORK_ON)) || [ -f "$WORK/$WORK_MARK" ]; } && L_WORK=$(rel_up "$WORK")
L_FF="" L_FP=""; [ "$FF_MODE" = system ] && L_FF=$FF_PATH L_FP=$FP_PATH
launcher_text() {
    printf '#!/bin/sh\n%s\n' "$LAUNCHER_MARK"
    printf '# cmr %s. Finds its own folder at run time (the cmr folder may be moved) and keeps\n' "$VERSION"
    printf '# %s next to it current. Do not edit: re-run install.sh (or --uninstall).\n' "$PATHS_CONF"
    printf 'CMR_VERSION=%s\n' "$(shq "$VERSION")"
    printf 'cmr_rooted=%s     # 1: the folder above this one is the cmr folder (bin/, demo/, work/)\n' "$L_ROOTED"
    printf 'cmr_demo=%s; cmr_work=%s   # relative = inside the folder above this one\n' "$(shq "$(rel_up "$WORKSPACE")")" "$(shq "$L_WORK")"
    printf 'cmr_ffmpeg=%s; cmr_ffprobe=%s   # empty = the env ffmpeg (ffmpeg-bin links into env/bin)\n' "$(shq "$L_FF")" "$(shq "$L_FP")"
    printf 'cmr_slate=%s\n' "$SLATE"
    cat <<'EOF'
# this file's folder: follow links by hand (macOS has no readlink -f)
p=$0 n=0
while [ -h "$p" ] && [ "$n" -lt 40 ]; do
    l=$(readlink "$p") || break
    case $l in /*) p=$l;; *) case $p in */*) p=${p%/*}/$l;; *) p=$l;; esac;; esac
    n=$((n + 1))
done
case $p in */*) d=${p%/*};; *) d=.;; esac
CMR_BIN=$(cd -P "${d:-/}" 2>/dev/null && pwd) || { echo "cmr: cannot find the launcher folder ($0)" >&2; exit 3; }
CMR_ENV=$CMR_BIN/env cmr_up=${CMR_BIN%/*}
# cmr-paths.conf: absolute paths for other tools, rewritten (temp file + mv) when the first
# line does not name this folder (moved, or written by an older launcher); never fails a run
cmr_conf=$CMR_BIN/cmr-paths.conf cmr_seen=
[ -r "$cmr_conf" ] && IFS= read -r cmr_seen <"$cmr_conf"
if [ "$cmr_seen" != "# for $CMR_BIN $CMR_VERSION" ] && [ -w "$CMR_BIN" ]; then
    cmr_q() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }
    cmr_kv() { printf '%s=%s\n' "$1" "$(cmr_q "$2")"; }
    cmr_abs() { case $1 in ''|/*) printf '%s' "$1";; *) printf '%s/%s' "$cmr_up" "$1";; esac; }
    r=; [ "$cmr_rooted" = 1 ] && r=$cmr_up
    tb=; td=; [ "$cmr_slate" = 1 ] && tb=$CMR_ENV/bin/tesseract td=$CMR_ENV/share/tessdata
    t=$cmr_conf.tmp.$$
    {
        printf '# for %s %s\n' "$CMR_BIN" "$CMR_VERSION"
        printf '# CheckMyRender paths: KEY=value in sh syntax, absolute, empty = not installed. Written\n'
        printf '# by the launcher next to this file (again whenever the folder moved). Do not edit.\n'
        cmr_kv CMR_VERSION "$CMR_VERSION"
        cmr_kv CMR_ROOT "$r"
        cmr_kv CMR_BIN "$CMR_BIN"
        cmr_kv CMR_LAUNCHER "$CMR_BIN/cmr"
        cmr_kv CMR_ENV "$CMR_ENV"
        cmr_kv CMR_FFMPEG "${cmr_ffmpeg:-$CMR_ENV/bin/ffmpeg}"
        cmr_kv CMR_FFPROBE "${cmr_ffprobe:-$CMR_ENV/bin/ffprobe}"
        cmr_kv CMR_TESSERACT "$tb"
        cmr_kv CMR_TESSDATA "$td"
        cmr_kv CMR_DEMO "$(cmr_abs "$cmr_demo")"
        cmr_kv CMR_WORK "$(cmr_abs "$cmr_work")"
    } 2>/dev/null >"$t" && mv -f "$t" "$cmr_conf" 2>/dev/null || rm -f "$t" 2>/dev/null
fi
PATH="$CMR_BIN/ffmpeg-bin:$PATH"; export PATH
if [ "$cmr_slate" = 1 ]; then
    CMR_TESSERACT=$CMR_ENV/bin/tesseract; export CMR_TESSERACT
    # tesseract has its tessdata folder compiled in: wrong once the folder moved
    [ -d "$CMR_ENV/share/tessdata" ] && { TESSDATA_PREFIX=$CMR_ENV/share/tessdata; export TESSDATA_PREFIX; }
fi
EOF
    if [ "$OS" = Darwin ]; then   # found on the Mac run 2026-10-26 (cron-like env -i)
        printf '# macOS: leptonica (tesseract) cannot open files under /tmp (it rewrites /tmp to the per-user\n'
        printf '# temp dir), so a run without TMPDIR (cron, launchd, env -i) gets the per-user temp dir\n'
        printf '[ -n "${TMPDIR:-}" ] || { t=$(getconf DARWIN_USER_TEMP_DIR 2>/dev/null) && [ -n "$t" ] && TMPDIR=$t && export TMPDIR; }\n'
    fi
    printf '# keep the environment Python clean of other Pythons'"'"' settings (-I: no PYTHON* variables,\n'
    printf '# no user site, not the current folder on sys.path)\n'
    printf 'unset PYTHONPATH PYTHONHOME; PYTHONNOUSERSITE=1; export PYTHONNOUSERSITE\n'
    printf 'exec "$CMR_ENV/bin/python" -I -m cmr "$@"\n'
}
# ffmpeg-bin links: relative into env/bin (they survive a move); the opt-in system ffmpeg absolute
FF_LINK=$FF_PATH FP_LINK=$FP_PATH
[ "$FF_MODE" = env ] && FF_LINK=../env/bin/ffmpeg FP_LINK=../env/bin/ffprobe
act "link $FFBIN/ffmpeg -> $FF_LINK and $FFBIN/ffprobe -> $FP_LINK"
act "write $LAUNCHER (and remove $PREFIX/$PATHS_CONF: the launcher writes it again on its first run)"
case $LINK_ACTION in
    create)  act "link $LINK -> $LAUNCHER";;
    keep)    log INFO "PATH link $LINK -> $LAUNCHER already in place";;
    repair)  act "repair the PATH link $LINK (pointed to $(readlink "$LINK"), which is gone) -> $LAUNCHER";;
    repoint) act "point the PATH link $LINK (was -> $(readlink "$LINK")) to $LAUNCHER";;
    migrate) act "replace the launcher file $LINK (previous layout) by a link to $LAUNCHER";;
esac
if ((DRY)); then
    launcher_text | sed 's/^/    | /'
else
    mkdir -p "$FFBIN" || die "cannot create $FFBIN" "check permissions"
    ln -sfn "$FF_LINK" "$FFBIN/ffmpeg" && ln -sfn "$FP_LINK" "$FFBIN/ffprobe" || die "cannot link ffmpeg into $FFBIN" "check permissions"
    launcher_text >"$LAUNCHER.tmp.$$" && chmod 755 "$LAUNCHER.tmp.$$" && mv -f "$LAUNCHER.tmp.$$" "$LAUNCHER" \
        || die "cannot write $LAUNCHER" "check permissions of $PREFIX" 1
    rm -f "$PREFIX/$PATHS_CONF"
    case $LINK_ACTION in
        create|repair|repoint|migrate)
            mkdir -p "$BIN_DIR" && ln -sfn "$LAUNCHER" "$LINK.tmp.$$" && mv -f "$LINK.tmp.$$" "$LINK" \
                || { rm -f "$LINK.tmp.$$"; die "cannot create the link $LINK" "check permissions of $BIN_DIR, or choose --bin-dir" 1; }
            case $LINK_ACTION in
                repair)  say "  Repaired the PATH link $LINK (its target was gone: folder moved?)";;
                repoint) say "  The PATH link $LINK now points to this install";;
                migrate) say "  Replaced the launcher file $LINK (previous layout) by a link to $LAUNCHER";;
            esac;;
    esac
fi
if [ -d "$OLD_FFENV" ]; then   # migration: the links no longer point into the old separate ffmpeg env
    act "remove the old separate ffmpeg environment $OLD_FFENV (ffmpeg now: $FF_PATH)"
    if ((!DRY)); then
        rm -rf "$OLD_FFENV" || die "cannot remove $OLD_FFENV" "check permissions" 1
        say "  Migrated: removed the old separate ffmpeg environment $OLD_FFENV (ffmpeg now: $FF_PATH)"
    fi
fi

