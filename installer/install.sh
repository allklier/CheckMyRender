done

# --- 8b. work area -----------------------------------------------------------------------------
# <work>: the user's own specs/, profiles/, jobs/, reports/, seeded ONCE from the bundle's work/
# (a spec, a profile, a job template with relative paths, a README). <work>/.cmr-work-files lists
# what was placed; with it present the installer never touches the work area again (not on
# --upgrade, not on --uninstall). An existing file is never overwritten.
step "Work area for your own files$( [ -n "$WORK" ] && printf ' (%s)' "$WORK")"
WORK_LIST="$WORK/$WORK_MARK"
if [ -z "$WORK" ]; then
    say "  Not set up: this install uses the previous layout (see the note at the start)"
elif ((!WORK_ON)); then
    say "  Skipped (--no-work)"
elif [ -f "$WORK_LIST" ]; then
    say "  Already set up (listed in $WORK_LIST); the installer never changes it"
elif [ ! -d "$BUNDLE/work" ]; then
    warn "this bundle has no work/ seed files: work area not set up"
else
    act "create $WORK/{specs,profiles,jobs,reports} and copy the seed files that are not there yet"
    if ((!DRY)); then
        mkdir -p "$WORK/specs" "$WORK/profiles" "$WORK/jobs" "$WORK/reports" \
            || die "cannot create the work area $WORK" "check permissions, or --no-work" 1
        placed="" nk=0
        while IFS= read -r -d '' f; do
            rel=${f#"$BUNDLE/work/"} dst="$WORK/${f#"$BUNDLE/work/"}"
            if [ -e "$dst" ]; then nk=$((nk + 1)); log INFO "work: kept existing $rel"; continue; fi
            mkdir -p "$(dirname "$dst")" && cp -p "$f" "$dst" || die "cannot copy to $dst" "check permissions and free space"
            placed+="$rel"$'\n'
        done < <(find "$BUNDLE/work" -type f -print0 | sort -z)
        printf '%s' "$placed" >"$WORK_LIST" || die "cannot write $WORK_LIST" "check permissions"
        say "  Set up $WORK: specs/, profiles/, jobs/ (job_template.yaml), reports/, README.md$( ((nk)) && printf ' (%d existing files kept)' "$nk")"
    fi
fi

# --- state ----------------------------------------------------------------------------------
act "write $STATE"
if ((!DRY)); then
    printf 'version=%s\nffmpeg_mode=%s\nffmpeg=%s\nslate=%s\ndemo=%s\nprefix=%s\nroot=%s\nworkspace=%s\nwork=%s\nbin_dir=%s\nconda=%s\ninstalled=%s\n' \
        "$VERSION" "$FF_MODE" "$FF_PATH" "$SLATE" "$DEMO" "$PREFIX" "$( ((L_ROOTED)) && printf '%s' "$ROOT")" "$WORKSPACE" "$WORK" "$BIN_DIR" "$CONDA" "$(date '+%Y-%m-%d %H:%M:%S')" >"$STATE"
fi

# --- 9. verify ------------------------------------------------------------------------------
step "Verify: cmr doctor and a self-test on a generated clip"
if ((DRY)); then
    printf '  [dry-run] would run: %s --version; %s doctor\n' "$LAUNCHER" "$( ((NO_LINK)) && printf '%s' "$LAUNCHER" || printf '%s' "$LINK")"
    ((SLATE)) && printf '  [dry-run] would run: %s --version\n' "$ENV/bin/tesseract"
    printf '  [dry-run] would generate a 2 s ProRes clip with %s and run: %s check CLIP --profile review --spec %s --report json\n' \
        "$FFBIN/ffmpeg" "$LAUNCHER" "$BUNDLE/templates/specs/spec_review_render.yaml"
else
    run "$LAUNCHER" --version || die "the launcher does not run cmr" "see the log; run again with --upgrade" 1
    [ -f "$PREFIX/$PATHS_CONF" ] || die "the launcher did not write $PREFIX/$PATHS_CONF" "see the log; run again with --upgrade" 1
    log INFO "$PATHS_CONF: $(tr '\n' ' ' <"$PREFIX/$PATHS_CONF")"
    VIA=$LAUNCHER; ((NO_LINK)) || VIA=$LINK     # doctor through the PATH link: proves it resolves
    out=$("$VIA" doctor 2>&1); rc=$?
    printf '%s\n' "$out" >>"$LOG"
    printf '%s\n' "$out" | sed 's/^/    /'
    [ $rc -eq 0 ] || die "cmr doctor reports problems (exit $rc)" "see the lines above; run again with --upgrade" 1
    if ((SLATE)); then
        tv=$("$ENV/bin/tesseract" --version 2>&1 | head -1)
        log INFO "tesseract: $tv"
        case $tv in tesseract\ 5.*) say "  tesseract ok: $tv";;
            *) die "tesseract does not run: '$tv'" "run again with --upgrade, or --no-slate" 1;; esac
        grep -q "tesseract (slate checks): NOT FOUND" <<<"$out" && die "cmr does not find tesseract" "see the log" 1
        "$ENV/bin/tesseract" --list-langs 2>&1 | grep -qx eng \
            || die "tesseract has no English language data (eng)" "see the log; run again with --upgrade" 1
    fi
    st=$(mktemp -d "$PREFIX/selftest.XXXXXX")
    run "$FFBIN/ffmpeg" -hide_banner -v error -y -f lavfi -i "testsrc2=size=320x180:rate=24000/1001" \
        -f lavfi -i "sine=frequency=1000:sample_rate=48000" -t 2 -c:v prores_ks -profile:v 2 \
        -pix_fmt yuv422p10le -c:a pcm_s24le -ac 2 "$st/selftest.mov" \
        || die "self-test: ffmpeg could not generate the test clip (kept: $st)" "see the log" 1
    run "$LAUNCHER" check "$st/selftest.mov" --profile review \
        --spec "$BUNDLE/templates/specs/spec_review_render.yaml" --report json -o "$st/report"
    rc=$?
    if [ $rc -le 2 ] && [ -s "$st/report/cmr_report_latest.json" ]; then
        say "  Self-test ok: cmr check ran on a generated clip (exit $rc; findings are expected, the clip does not match the spec)"
        rm -rf "$st"
    else
        die "self-test: cmr check failed (exit $rc, report missing?); files kept in $st" "see the log and $(printf '%s' "$LOG_DIR")/cmr.log" 1
    fi
fi

# --- 10. demo spots -------------------------------------------------------------------------
# The bundled generator (demo/make_spot.py = tests/slate/make_spot.py) makes a 10 s slated
# ProRes spot (~63 MB) that matches templates/starter unedited, plus spots with planted errors.
# Created ONCE per workspace: <workspace>/.cmr-demo-files lists what was placed (workspace-
# relative paths); with that record present nothing is generated again (a demo file the user
# deleted or moved stays gone). An existing file is never overwritten. The demo files are not
# templates: they are not in .cmr-installed-files and never updated. A failure only warns.
step "Demo spots (a clean slated spot to try cmr on, and spots with planted errors)"
GEN="$BUNDLE/demo/make_spot.py"
STARTER_MEDIA="templates/starter/media"
demo_hand="mkdir -p ~/cmr-demo && PATH=$(shq "$FFBIN"):\$PATH $(qcmd "$ENV/bin/python" "$GEN") ~/cmr-demo --short"
if ((!DEMO)); then
    say "  Skipped (--no-demo). To make them later: $demo_hand"
elif [ -f "$DEMO_LIST" ]; then
    say "  Already created before (listed in $DEMO_LIST); nothing generated again"
elif [ ! -f "$GEN" ]; then
    warn "this bundle has no demo generator (demo/make_spot.py): no demo spots created"
elif ((DRY)); then
    printf '  [dry-run] would run (into a temporary folder in %s): PATH=%s:$PATH %s TMP/main --short\n' \
        "$WORKSPACE" "$FFBIN" "$(qcmd "$ENV/bin/python" "$GEN")"
    printf '  [dry-run] would run: ... %s TMP/typo --short --defect client_typo\n' "$(basename "$GEN")"
    printf '  [dry-run] would place: %s/<clean spot>.mov, %s/demo_spots/clean/, %s/demo_spots/errors/many_errors/, %s/demo_spots/errors/client_typo/ (existing files are kept)\n' \
        "$WORKSPACE/$STARTER_MEDIA" "$WORKSPACE" "$WORKSPACE" "$WORKSPACE"
else
    say "  Generating (about 60 MB per spot, 10-60 s) ..."
    t0=$SECONDS
    gt=$(mktemp -d "$WORKSPACE/.cmr-demo-tmp.XXXXXX") || die "cannot write to $WORKSPACE" "check permissions"
    gen() {   # gen OUTDIR [ARGS...]: run the generator with the env Python and cmr's ffmpeg
        local o=$1; shift
        log INFO "run: demo generator $(qcmd "$o" "$@")"
        env -u PYTHONPATH -u PYTHONHOME PYTHONNOUSERSITE=1 PATH="$FFBIN:$PATH" \
            "$ENV/bin/python" "$GEN" "$o" --short "$@" >>"$gt/gen.out" 2>&1
    }
    if gen "$gt/main" && gen "$gt/typo" --defect client_typo; then
        cat "$gt/gen.out" >>"$LOG"
        placed="" bytes=0
        place() {   # place SRC REL: move a generated file to WORKSPACE/REL unless a file is there
            local dst="$WORKSPACE/$2"
            if [ -e "$dst" ]; then log INFO "demo: kept existing $2"; return 0; fi
            mkdir -p "$(dirname "$dst")" && mv -f "$1" "$dst" || return 1
            placed+="$2"$'\n'; bytes=$((bytes + $(wc -c <"$dst")))
        }
        ok=1
        for f in "$gt"/main/clean/*.mov; do
            n=$(basename "$f")
            place "$f" "demo_spots/clean/$n" || ok=0
            # the same spot ready to check in the starter folder (a hard link where possible)
            if [ ! -e "$WORKSPACE/$STARTER_MEDIA/$n" ] && [ -f "$WORKSPACE/demo_spots/clean/$n" ]; then
                mkdir -p "$WORKSPACE/$STARTER_MEDIA" \
                    && { ln "$WORKSPACE/demo_spots/clean/$n" "$WORKSPACE/$STARTER_MEDIA/$n" 2>/dev/null \
                         || cp -p "$WORKSPACE/demo_spots/clean/$n" "$WORKSPACE/$STARTER_MEDIA/$n"; } \
                    && placed+="$STARTER_MEDIA/$n"$'\n' || ok=0
            fi
        done
        for f in "$gt"/main/errors/*.mov; do place "$f" "demo_spots/errors/many_errors/$(basename "$f")" || ok=0; done
        place "$gt/main/manifest.yaml" "demo_spots/errors/many_errors/manifest.yaml" || ok=0
        for f in "$gt"/typo/client_typo/*.mov; do place "$f" "demo_spots/errors/client_typo/$(basename "$f")" || ok=0; done
        place "$gt/typo/manifest.yaml" "demo_spots/errors/client_typo/manifest.yaml" || ok=0
        [ -n "$placed" ] && printf '%s' "$placed" >"$DEMO_LIST"
        if ((ok)); then
            say "  Created in $((SECONDS - t0)) s ($((bytes / 1048576)) MB): the clean spot in $WORKSPACE/$STARTER_MEDIA (and demo_spots/clean),"
            say "  spots with planted errors in $WORKSPACE/demo_spots/errors (client_typo: one slate typo; many_errors: many planted errors, listed in its manifest.yaml)"
        else
            warn "the demo spots could not all be placed in $WORKSPACE (see the log); the install itself is fine"
        fi
    else
        cat "$gt/gen.out" >>"$LOG"
        warn "the demo spots could not be generated (the install itself is fine): $(tail -1 "$gt/gen.out")"
        say "  Run the installer again to retry, or make them by hand: $demo_hand"
        say "  (a missing font: set CMR_TEST_FONT and CMR_TEST_FONT_REGULAR to a bold and a regular .ttf file)"
    fi
    rm -rf "$gt"
fi

