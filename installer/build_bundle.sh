#!/usr/bin/env bash
# Build the release bundle dist/cmr-<version>-bundle.tar.gz from this source tree (no network:
# the wheel is built with pip --no-index --no-build-isolation from the installed setuptools).
# Contents: install.sh, environment.yml, required_filters.txt (from the built package: the same
# list `cmr doctor` checks), VERSION, README.txt, README.md, USERGUIDE.md (templates/README.md
# links to ../USERGUIDE.md), wheels/<cmr wheel>, examples/ and templates/ without any CLAUDE.md,
# SHA256SUMS. Details: installer/CLAUDE.md.
set -u -o pipefail

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(dirname "$HERE")
OUT="$HERE/dist" WHEEL="" PY=python3

usage() {
    cat <<EOF
Usage: build_bundle.sh [-o OUTDIR] [--wheel FILE] [--python PY]
  -o OUTDIR     output folder (default installer/dist)
  --wheel FILE  use this pre-built cmr wheel instead of building one (its version must match)
  --python PY   Python used to build the wheel and read the filter list (default python3;
                needs setuptools + wheel, PyYAML, jsonschema)
EOF
}
die() { printf 'build_bundle: ERROR: %s\n' "$1" >&2; exit 1; }
while [ $# -gt 0 ]; do
    case $1 in
        -o) [ $# -ge 2 ] || die "-o needs a folder"; OUT=$2; shift;;
        --wheel) [ $# -ge 2 ] || die "--wheel needs a file"; WHEEL=$2; shift;;
        --python) [ $# -ge 2 ] || die "--python needs an interpreter"; PY=$2; shift;;
        -h|--help) usage; exit 0;;
        *) usage >&2; exit 2;;
    esac
    shift
done

VERSION=$(sed -n 's/^__version__ *= *"\([^"]*\)".*/\1/p' "$ROOT/src/cmr/__init__.py")
[ -n "$VERSION" ] || die "cannot read __version__ from src/cmr/__init__.py"
TMP=$(mktemp -d) || die "mktemp failed"
trap 'rm -rf "$TMP"' EXIT
NAME="cmr-$VERSION"
STAGE="$TMP/stage/$NAME"
mkdir -p "$STAGE/wheels" "$TMP/wheelbuild" || die "cannot create $STAGE"

if [ -z "$WHEEL" ]; then   # build in a copy so the source tree gets no build/ or *.egg-info
    for f in pyproject.toml README.md LICENSE src profiles; do
        [ -e "$ROOT/$f" ] && cp -r "$ROOT/$f" "$TMP/wheelbuild/"
    done
    find "$TMP/wheelbuild" -name __pycache__ -prune -exec rm -rf {} +
    "$PY" -m pip wheel --no-deps --no-index --no-build-isolation -q -w "$TMP/wheels" "$TMP/wheelbuild" \
        || die "wheel build failed (needs setuptools and wheel for $PY; no network is used)"
    WHEEL=$(ls "$TMP"/wheels/*.whl 2>/dev/null | head -1)
    [ -n "$WHEEL" ] || die "no wheel was built"
fi
[ -f "$WHEEL" ] || die "wheel not found: $WHEEL"
case $(basename "$WHEEL") in
    *-"$VERSION"-*.whl) ;;
    *) die "wheel $(basename "$WHEEL") does not match version $VERSION";;
esac
cp "$WHEEL" "$STAGE/wheels/" || die "cannot copy the wheel"

# check the wheel and read the required ffmpeg filters from the package itself (one source of
# truth: the checks' requires_filters, the list `cmr doctor` uses)
"$PY" -I - "$STAGE/wheels/$(basename "$WHEEL")" "$TMP/unpacked" >"$STAGE/required_filters.txt" <<'EOF' \
    || die "wheel check failed (see above)"
import sys, zipfile
whl, dest = sys.argv[1], sys.argv[2]
with zipfile.ZipFile(whl) as z:
    names = z.namelist()
    z.extractall(dest)
problems = [n for n in names if n.rsplit("/", 1)[-1] == "CLAUDE.md"]
if problems:
    sys.exit(f"wheel contains CLAUDE.md files: {problems}")
for need in ("cmr/__init__.py", "cmr/cli.py", "cmr/profiles/final.yaml"):
    if need not in names:
        sys.exit(f"wheel lacks {need} (stock profiles must ship as package data)")
sys.path.insert(0, dest)
from cmr import engine
engine.load_checks()
if engine.IMPORT_ERRORS:
    sys.exit(f"check plugins fail to import: {engine.IMPORT_ERRORS}")
need = sorted({f for c in engine.REGISTRY.values() for f in c.requires_filters})
print("# ffmpeg filters cmr's checks need (generated by build_bundle.sh from the package)")
print("\n".join(need))
EOF

cp "$HERE/install.sh" "$HERE/environment.yml" "$STAGE/" || die "cannot copy installer files"
cp "$ROOT/README.md" "$ROOT/USERGUIDE.md" "$STAGE/" || die "cannot copy README.md / USERGUIDE.md"
chmod 755 "$STAGE/install.sh"
printf '%s\n' "$VERSION" >"$STAGE/VERSION"
for top in examples templates; do   # without CLAUDE.md (and no caches)
    (cd "$ROOT" && find "$top" -type f ! -name CLAUDE.md ! -name '*.pyc' ! -path '*/__pycache__/*' -print0) |
        while IFS= read -r -d '' f; do
            mkdir -p "$STAGE/$(dirname "$f")" && cp -p "$ROOT/$f" "$STAGE/$f" || exit 1
        done || die "cannot copy $top"
done
cat >"$STAGE/README.txt" <<EOF
CheckMyRender $VERSION - render QC tool (command line: cmr)

Install (per user, no sudo; Linux x86_64, tested on Rocky Linux 9):

    tar xzf $NAME-bundle.tar.gz
    $NAME/install.sh --dry-run      # shows every step, changes nothing
    $NAME/install.sh                # installs; add --no-slate to skip the slate OCR (~0.9 GB)

The installer creates its own conda environment (Python 3.12, from conda-forge only) in
~/.local/share/cmr/env, a 'cmr' launcher in ~/.local/bin and copies examples/ and templates/ to
~/cmr-workspace. It uses an existing conda (Anaconda, Miniconda, Miniforge) without changing its
base environment, or offers to install Miniforge. The system ffmpeg is used when it is new
enough (>= 5.1 with all filters cmr needs), otherwise a conda-forge ffmpeg goes into cmr's
environment; the system ffmpeg is never changed. Needs network access to conda.anaconda.org
and about 3 GB free disk space (1.5 GB with --no-slate).

Production Python policy: never update or replace the system Python on a production machine
(Flame and the OS rely on it); cmr runs from its own conda environment.

Other options: $NAME/install.sh --help (--prefix, --workspace, --upgrade, --uninstall, --yes).
Install log: ~/.cache/cmr/logs/install.log. After install: cmr doctor.
Files: USERGUIDE.md (the user guide), README.md, wheels/ (the cmr package), environment.yml
(conda packages), required_filters.txt, SHA256SUMS (checked by the installer before it
changes anything).
EOF

(cd "$STAGE" && find . -type f ! -name SHA256SUMS -printf '%P\0' | sort -z | xargs -0 sha256sum >SHA256SUMS) \
    || die "checksums failed"
mkdir -p "$OUT" || die "cannot create $OUT"
TAR="$OUT/$NAME-bundle.tar.gz"
tar --sort=name --owner=0 --group=0 --numeric-owner -C "$TMP/stage" -czf "$TAR" "$NAME" || die "tar failed"
(cd "$OUT" && sha256sum "$(basename "$TAR")" >"$(basename "$TAR").sha256")
printf 'bundle: %s\nsha256: %s\n' "$TAR" "$(cut -d' ' -f1 "$TAR.sha256")"
